// =============================================================================
// HELPER FUNCTIONS
// =============================================================================

export const getGameById = (id: string): GameConfig | undefined => {
  return ARCADE_GAMES.find(game => game.id === id);
};

export const getGamesByCategory = (category: string): GameConfig[] => {
  return ARCADE_GAMES.filter(game => game.category === category);
};

export const getGamesWithAI = (): GameConfig[] => {
  return ARCADE_GAMES.filter(game => game.hasAI);
};

export const getGamesWithMultiplayer = (): GameConfig[] => {
  return ARCADE_GAMES.filter(game => game.hasMultiplayer);
};

export const getGamesWithGamepad = (): GameConfig[] => {
  return ARCADE_GAMES.filter(game => game.controls.includes('gamepad'));
};

export const searchGames = (query: string): GameConfig[] => {
  const lowerQuery = query.toLowerCase();
  return ARCADE_GAMES.filter(game => 
    game.title.toLowerCase().includes(lowerQuery) ||
    game.description.toLowerCase().includes(lowerQuery) ||
    game.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
  );
};
